"""Generates the pdh.dll proxy exports (proxy_pdh.asm, proxy_pdh.def, proxy_pdh.h) from the system pdh.dll:
every export jumps through px_ptrs[i], filled by proxy_init (proxy.c) from the real pdh.dll in System32."""
import os, pefile
HERE = os.path.dirname(os.path.abspath(__file__))
pe = pefile.PE(os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "pdh.dll"))
syms = [(s.ordinal, s.name.decode()) for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name]
asm = ["; generated by gen_proxy.py: pdh.dll exports -> the real pdh.dll (proxy.c fills px_ptrs)",
       "PUBLIC px_ptrs", ".data", "px_ptrs dq %d dup(0)" % len(syms), ".code"]
for i, (o, n) in enumerate(syms):
    asm += ["px_%s PROC" % n, "    jmp qword ptr [px_ptrs + %d]" % (8 * i), "px_%s ENDP" % n]
asm.append("END")
open(os.path.join(HERE, "proxy_pdh.asm"), "w").write("\n".join(asm) + "\n")
d = ["; generated by gen_proxy.py", "EXPORTS"] + ["    %s=px_%s @%d" % (n, n, o) for o, n in syms]
open(os.path.join(HERE, "proxy_pdh.def"), "w").write("\n".join(d) + "\n")
h = ["/* generated by gen_proxy.py: names of the pdh.dll exports, in px_ptrs order */",
     "#define PX_COUNT %d" % len(syms), "static const char *const k_px_names[PX_COUNT] = {"]
h += ['    "%s",' % n for o, n in syms] + ["};"]
open(os.path.join(HERE, "proxy_pdh.h"), "w").write("\n".join(h) + "\n")
print(len(syms), "exports")
